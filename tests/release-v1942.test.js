import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { GUIDE_SECTIONS, searchGuide } from '../src/guide.js';
import { dictionaries } from '../src/i18n.js';

const read = (f) => readFileSync(new URL(`../${f}`, import.meta.url), 'utf8');

test('v1.9.42 release: version, cache v158, prices, e-payments, link import, CSV export, updated guide', () => {
  assert.match(read('package.json'), /"version": "1\.9\.42"/);
  assert.equal((read('index.html').match(/data-no-i18n>1\.9\.42</g) || []).length, 2);
  const html = read('index.html');
  assert.match(html, /styles\.css\?v=158/);
  assert.match(html, /src\/app\.js\?v=158/);
  assert.doesNotMatch(html, /v=158-preview/);
  const sw = read('sw.js');
  assert.match(sw, /CACHE_VERSION = 'v158';/);
  assert.doesNotMatch(sw, /CACHE_VERSION = 'v158-preview'/);
  assert.match(sw, /styles\.css\?v=158'/);
  assert.match(sw, /src\/app\.js\?v=158'/);
  assert.match(sw, /src\/price-history\.js/);
  assert.match(sw, /src\/epayment-target\.js/);
  assert.match(sw, /src\/csv-export\.js/);
  const app = read('src/app.js');
  assert.match(app, /data-action="price-history"/);
  assert.match(app, /Επικόλληση λινκ απόδειξης/);
  assert.match(app, /Πληρώθηκε με μετρητά/);
  assert.match(app, /📊 Εξαγωγή εξόδων \(Excel\)/);
  assert.match(app, /💳 Στόχος ηλεκτρονικών πληρωμών|Στόχος ηλεκτρονικών πληρωμών/);
  assert.doesNotMatch(app, /Γιάννης /);
  assert.doesNotMatch(app, /Σκολαρ|Skolarikis/);
  assert.match(read('src/price-history.js'), /export function productPriceHistory\(/);
  assert.match(read('src/epayment-target.js'), /export function electronicPaymentTarget\(/);
  assert.match(read('src/epayment-target.js'), /export const EPAY_RATE = 0\.3;/);
  assert.match(read('src/epayment-target.js'), /export const EPAY_TARGET_CAP = 20000;/);
  assert.match(read('src/csv-export.js'), /export function buildExpenseCsv\(/);
  assert.match(read('src/receipt.js'), /export function isReceiptLink\(/);
  assert.match(read('src/receipt.js'), /export function extractReceiptLink\(/);
  const manifest = read('manifest.webmanifest');
  assert.match(manifest, /"share_target"/);
  const guide = read('src/guide.js');
  assert.match(guide, /Τι νέο στην 1\.9\.42/);
  assert.match(guide, /📈 Τελευταίες τιμές/);
  assert.match(guide, /🔗 Επικόλληση λινκ απόδειξης/);
  assert.match(guide, /📊 Εξαγωγή εξόδων \(Excel\)/);
  assert.doesNotMatch(guide, /Γιάννης /);
  assert.doesNotMatch(guide, /Σκολαρ|Skolarikis/);
  assert.ok(searchGuide('1.9.42').some((s) => s.id === 'whats-new'));
  assert.ok(searchGuide('1.9.41').some((s) => s.id === 'whats-new'));
  const whats = GUIDE_SECTIONS.find((s) => s.id === 'whats-new');
  assert.equal(whats.title, 'Τι νέο στην 1.9.42');
  assert.ok(dictionaries.en[whats.title]);
  assert.ok(dictionaries.en[whats.intro]);
  for (const b of whats.bullets) assert.ok(dictionaries.en[b], `EN missing: ${b}`);
});
