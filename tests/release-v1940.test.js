import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { GUIDE_SECTIONS, searchGuide } from '../src/guide.js';
import { dictionaries } from '../src/i18n.js';

const read = (f) => readFileSync(new URL(`../${f}`, import.meta.url), 'utf8');

test('v1.9.40 release: version, cache v150, month card, faster scan, pantry-to-list, privacy box, category memory', () => {
  assert.match(read('package.json'), /"version": "1\.9\.44"/);
  assert.equal((read('index.html').match(/data-no-i18n>1\.9\.44</g) || []).length, 2);
  const html = read('index.html');
  assert.match(html, /styles\.css\?v=160/);
  assert.match(html, /src\/app\.js\?v=160/);
  assert.doesNotMatch(html, /v=160-preview/);
  const sw = read('sw.js');
  assert.match(sw, /CACHE_VERSION = 'v160';/);
  assert.doesNotMatch(sw, /CACHE_VERSION = 'v160-preview'/);
  assert.match(sw, /styles\.css\?v=160'/);
  assert.match(sw, /src\/app\.js\?v=160'/);
  const app = read('src/app.js');
  assert.match(app, /function renderHomeMonthBody\(/);
  assert.match(app, /class="home-donut"/);
  assert.match(app, /id="home-month-legend"/);
  assert.match(app, /Τελείωσε; Βάλ’ το στη λίστα/);
  assert.match(app, /Τι δεν μαζεύουμε/);
  assert.match(app, /Προτάθηκε από την προηγούμενη απόδειξη του ίδιου καταστήματος/);
  assert.doesNotMatch(app, /Γιάννης /);
  assert.doesNotMatch(app, /Σκολαρ|Skolarikis/);
  const guide = read('src/guide.js');
  assert.match(guide, /Τι νέο στην 1\.9\.40/);
  assert.doesNotMatch(guide, /Γιάννης /);
  assert.ok(searchGuide('1.9.40').some((s) => s.id === 'whats-new'));
  assert.ok(searchGuide('1.9.39').some((s) => s.id === 'whats-new'));
  const whats = GUIDE_SECTIONS.find((s) => s.id === 'whats-new');
  assert.match(whats.title, /Τι νέο στην 1\.9\.\d+/);
  assert.ok(dictionaries.en[whats.title]);
  assert.ok(dictionaries.en[whats.intro]);
  for (const b of whats.bullets) assert.ok(dictionaries.en[b], `EN missing: ${b}`);
});
